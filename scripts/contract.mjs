import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const mode = process.argv[2];
if (mode !== 'generate' && mode !== 'check') {
  throw new Error('Chọn contract:generate hoặc contract:check.');
}

const exporter = new URL(
  '../apps/api/dist/platform/openapi/export.js',
  import.meta.url,
);
const destination = new URL(
  '../packages/api-contract/generated/',
  import.meta.url,
);
const exported = spawnSync(process.execPath, [fileURLToPath(exporter)], {
  encoding: 'utf8',
  timeout: 30000,
  maxBuffer: 16 * 1024 * 1024,
  windowsHide: true,
});
if (exported.error || exported.status !== 0) {
  throw new Error(
    exported.stderr?.trim() || 'Không thể xuất OpenAPI từ API đã build.',
  );
}

const document = JSON.parse(exported.stdout);
const types = astToString(await openapiTS(document, { alphabetize: true }));
const artifacts = {
  'openapi.json': JSON.stringify(document, null, 2) + '\n',
  'index.d.ts': '// Generated by npm run contract:generate\n\n' + types,
};

if (mode === 'generate') {
  await mkdir(destination, { recursive: true });
  for (const [name, contents] of Object.entries(artifacts)) {
    await writeFile(new URL(name, destination), contents, 'utf8');
  }
  console.log('Đã xuất OpenAPI và type vào packages/api-contract/generated/.');
} else {
  const differences = [];
  for (const [name, expected] of Object.entries(artifacts)) {
    const actual = await readFile(new URL(name, destination), 'utf8').catch(
      (error) => {
        if (error.code === 'ENOENT') return '';
        throw error;
      },
    );
    if (actual.replace(/\r\n/g, '\n') !== expected) differences.push(name);
  }
  if (differences.length > 0) {
    console.error(
      `Hợp đồng API đã lệch ở ${differences.join(', ')}. Chạy npm run contract:generate.`,
    );
    process.exitCode = 1;
  } else {
    console.log('OpenAPI và type khớp với mã nguồn NestJS.');
  }
}
